-- ==============================================================================
-- 9. THIẾT LẬP CHÍNH SÁCH BẢO MẬT NGHIÊM NGẶT (STRICT POLICIES)
-- ==============================================================================

-- A. BẢNG FEEDBACKS (Góp ý):
-- 1. Khách vãng lai (anon) chỉ được INSERT (Độ dài nội dung >= 3 và <= 2000 ký tự)
CREATE POLICY "Public can insert feedback" ON public.feedbacks
    FOR INSERT TO anon, authenticated
    WITH CHECK (
        LENGTH(content) >= 3 AND LENGTH(content) <= 2000
    );

-- 2. Khách vãng lai CHỈ ĐƯỢC ĐỌC các góp ý đã được duyệt (approved = true)
CREATE POLICY "Public can read approved feedbacks" ON public.feedbacks
    FOR SELECT TO anon, authenticated
    USING (approved = true);

-- 3. Quản trị viên (authenticated) hoặc Service Role toàn quyền (ALL)
CREATE POLICY "Admin full access feedbacks" ON public.feedbacks
    FOR ALL TO authenticated, service_role
    USING (true)
    WITH CHECK (true);


-- B. BẢNG LUCKY_SPINS (Vòng quay Minigame):
-- 1. Khách vãng lai chỉ được INSERT lượt quay (SĐT hợp lệ)
CREATE POLICY "Public can insert lucky spin" ON public.lucky_spins
    FOR INSERT TO anon, authenticated
    WITH CHECK (
        LENGTH(customer_phone) >= 8 AND LENGTH(customer_phone) <= 20
    );

-- 2. Khách vãng lai chỉ được SELECT để kiểm tra cooldown của chính thiết bị / SĐT trong 24h
CREATE POLICY "Public can verify own lucky spin" ON public.lucky_spins
    FOR SELECT TO anon, authenticated
    USING (
        created_at >= (now() - INTERVAL '24 hours')
    );

-- 3. Quản trị viên toàn quyền
CREATE POLICY "Admin full access lucky spins" ON public.lucky_spins
    FOR ALL TO authenticated, service_role
    USING (true)
    WITH CHECK (true);


-- C. BẢNG CUSTOMERS (Khách hàng & Leads):
-- 1. Khách vãng lai CHỈ được INSERT (Ghi nhận thông tin tham gia minigame / check-in), KHÔNG ĐƯỢC SELECT / UPDATE / DELETE để bảo mật PII
CREATE POLICY "Public can register as customer lead" ON public.customers
    FOR INSERT TO anon, authenticated
    WITH CHECK (
        LENGTH(contact) >= 5
    );

-- 2. Quản trị viên toàn quyền quản lý khách hàng & điểm
CREATE POLICY "Admin full access customers" ON public.customers
    FOR ALL TO authenticated, service_role
    USING (true)
    WITH CHECK (true);


-- D. BẢNG POINT_TRANSACTIONS (Lịch sử điểm):
-- 1. Chỉ Quản trị viên mới có quyền xem và ghi sổ điểm
CREATE POLICY "Admin full access point transactions" ON public.point_transactions
    FOR ALL TO authenticated, service_role
    USING (true)
    WITH CHECK (true);


-- E. BẢNG MENU_ITEMS (Thực đơn):
-- 1. Khách vãng lai CHỈ được xem món đang mở bán (SELECT)
