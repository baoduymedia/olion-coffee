-- Feedbacks Policies
CREATE POLICY "Cho phép khách hàng thêm góp ý" ON public.feedbacks FOR INSERT WITH CHECK (true);
CREATE POLICY "Cho phép xem đánh giá đã duyệt" ON public.feedbacks FOR SELECT USING (approved = true);
CREATE POLICY "Admin toàn quyền feedbacks" ON public.feedbacks FOR ALL USING (true);

-- Lucky Spins Policies
CREATE POLICY "Cho phép ghi nhận kết quả quay" ON public.lucky_spins FOR INSERT WITH CHECK (true);
CREATE POLICY "Admin toàn quyền lucky_spins" ON public.lucky_spins FOR ALL USING (true);

-- Customers Policies
CREATE POLICY "Cho phép ghi nhận khách hàng" ON public.customers FOR INSERT WITH CHECK (true);
CREATE POLICY "Admin toàn quyền customers" ON public.customers FOR ALL USING (true);

-- Point Transactions Policies
CREATE POLICY "Public xem point_transactions" ON public.point_transactions FOR SELECT USING (true);
CREATE POLICY "Admin toàn quyền point_transactions" ON public.point_transactions FOR ALL USING (true);

-- Menu Items Policies
CREATE POLICY "Public xem menu_items" ON public.menu_items FOR SELECT USING (true);
CREATE POLICY "Admin toàn quyền menu_items" ON public.menu_items FOR ALL USING (true);

-- 8. BẬT REALTIME CHO TẤT CẢ CÁC BẢNG
