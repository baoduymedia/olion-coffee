DROP POLICY IF EXISTS "Admin toàn quyền point_transactions" ON public.point_transactions;
DROP POLICY IF EXISTS "Public xem point_transactions" ON public.point_transactions;

DROP POLICY IF EXISTS "Public xem menu_items" ON public.menu_items;
