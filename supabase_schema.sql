-- 1. BẢNG GÓP Ý & ĐÁNH GIÁ (feedbacks)
CREATE TABLE IF NOT EXISTS public.feedbacks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL DEFAULT 'Khách ghé quán',
    contact TEXT,
    rating INTEGER NOT NULL CHECK (rating >= 1 AND rating <= 5),
    content TEXT NOT NULL,
    image_url TEXT,
    device_id TEXT,
    approved BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Bổ sung cột device_id nếu chưa có
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='feedbacks' AND column_name='device_id') THEN
        ALTER TABLE public.feedbacks ADD COLUMN device_id TEXT;
    END IF;
END $$;

-- 2. BẢNG VÒNG QUAY MAY MẮN (lucky_spins)
CREATE TABLE IF NOT EXISTS public.lucky_spins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name TEXT DEFAULT 'Khách quay minigame',
    customer_phone TEXT NOT NULL,
    prize_name TEXT NOT NULL,
    promo_code TEXT NOT NULL,
    device_id TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Bổ sung cột device_id nếu chưa có
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='lucky_spins' AND column_name='device_id') THEN
        ALTER TABLE public.lucky_spins ADD COLUMN device_id TEXT;
    END IF;
END $$;

-- 3. BẢNG KHÁCH HÀNG & TÍCH ĐIỂM (customers)
CREATE TABLE IF NOT EXISTS public.customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    contact TEXT NOT NULL UNIQUE,
    points INTEGER DEFAULT 0 NOT NULL,
    tier TEXT DEFAULT 'Thành viên' NOT NULL,
    source TEXT DEFAULT 'Website Olion Coffee',
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 4. BẢNG LỊCH SỬ GIAO DỊCH ĐIỂM (point_transactions)
CREATE TABLE IF NOT EXISTS public.point_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT REFERENCES public.customers(id) ON DELETE CASCADE,
    customer_contact TEXT NOT NULL,
    action_type TEXT NOT NULL CHECK (action_type IN ('earn', 'redeem', 'adjust')),
    points_change INTEGER NOT NULL,
    balance_after INTEGER NOT NULL DEFAULT 0,
    reason TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. BẢNG QUẢN LÝ THỰC ĐƠN (menu_items)
CREATE TABLE IF NOT EXISTS public.menu_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    price NUMERIC NOT NULL DEFAULT 0,
    category TEXT NOT NULL DEFAULT 'Cà phê',
    image_url TEXT,
    badge TEXT DEFAULT '',
    description TEXT,
    is_available BOOLEAN DEFAULT TRUE NOT NULL,
    sort_order INTEGER DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- ==============================================================================
-- 6. TẠO INDEXES TỐI ƯU HIỆU NĂNG CHO CÁC TRUY VẤN CHECK RATE LIMIT
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_lucky_spins_device_time ON public.lucky_spins (device_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_lucky_spins_phone_time ON public.lucky_spins (customer_phone, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_feedbacks_device_time ON public.feedbacks (device_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_feedbacks_approved ON public.feedbacks (approved, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_customers_contact ON public.customers (contact);

-- ==============================================================================
-- 7. BẬT ROW LEVEL SECURITY (RLS) TRÊN TẤT CẢ CÁC BẢNG
